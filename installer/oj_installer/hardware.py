"""Hardware module generation and bootloader wiring.

The shape mirrors the reference attended installer: nixos-generate-config, a
generated hardware module that follows the flake module contract, facter
report, and LUKS device lines keyed by the encrypted parent UUID.
"""

import json
import os
import re
import subprocess
from pathlib import Path

from . import flake_structure, paths, template

LUKS_DEVICE_LINE = re.compile(r'boot\.initrd\.luks\.devices\."([^"]+)"\.device\s*=')


class HardwareError(Exception):
    pass


def run(command, input_text=None):
    result = subprocess.run(
        command,
        input=input_text,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )
    if result.returncode != 0:
        raise HardwareError(
            "command failed ({}): {}\n{}{}".format(
                result.returncode,
                " ".join(str(part) for part in command),
                result.stdout,
                result.stderr,
            )
        )
    return result.stdout


def output(command):
    return run(command).strip()


def root_is_btrfs(hardware):
    return re.search(
        r'fileSystems\."/"\s*=\s*\{[^}]*fsType\s*=\s*"btrfs"',
        hardware,
        re.DOTALL,
    ) is not None


def bootloader_module(firmware, device, extra_lines, btrfs_root):
    lines = []
    if firmware == "efi":
        lines += [
            "boot.loader.systemd-boot.enable = true;",
            "boot.loader.efi.canTouchEfiVariables = true;",
        ]
    else:
        lines += [
            "boot.loader.grub.enable = true;",
            "boot.loader.grub.device = {};".format(template.nix_string(device)),
            "boot.loader.grub.useOSProber = true;",
        ]
        if btrfs_root:
            lines.append('boot.loader.grub.fsIdentifier = "provided";')
    lines += extra_lines
    return "\n".join("    " + line if line else line for line in lines)


def hardware_module(hardware, firmware, device, extra_lines):
    indented = "\n".join("    " + line if line else line for line in hardware.splitlines())
    return """# Generated by the Ojuny minimal installer. Do not edit by hand.
{{ self, inputs, ... }}: {{

  flake.modules.nixos.system-hardware =
{hardware}
  ;

  flake.modules.nixos.system-bootloader = {{ pkgs, ... }}: {{
{bootloader}
  }};

}}
""".format(
        hardware=indented,
        bootloader=bootloader_module(
            firmware, device, extra_lines, root_is_btrfs(hardware)
        ),
    )


def generate_hardware(root):
    run(["nixos-generate-config", "--root", str(root)])
    hardware = Path(root) / "etc/nixos/hardware-configuration.nix"
    if not hardware.exists():
        raise HardwareError("nixos-generate-config did not write a hardware configuration")
    text = hardware.read_text(encoding="utf-8")
    for name in ("configuration.nix", "hardware-configuration.nix"):
        leftover = Path(root) / "etc/nixos" / name
        if leftover.exists():
            leftover.unlink()
    return text


def open_crypt_devices():
    report = json.loads(output(["lsblk", "-J", "-o", "NAME,TYPE,UUID"]))
    devices = {}

    def walk(node, parent_uuid=None):
        if node.get("type") == "crypt":
            name = node.get("name")
            uuid = parent_uuid or node.get("uuid")
            if name and uuid:
                devices[name] = uuid
        for child in node.get("children") or []:
            walk(child, node.get("uuid") or parent_uuid)

    for node in report.get("blockdevices", []):
        walk(node)
    return devices


def hardware_module_path(staging):
    found = flake_structure.find_modules(staging, "system-hardware") or \
        flake_structure.find_modules(staging, "system-bootloader")
    if found:
        return Path(found[0])
    return Path(staging) / "modules/00-hardware.nix"


def sanitize_hardware_module(staging):
    path = hardware_module_path(staging)
    if not path.exists():
        return path
    lines = [
        line
        for line in path.read_text(encoding="utf-8").splitlines()
        if "hardware.facter.reportPath" not in line
    ]
    crypt = open_crypt_devices()

    existing = {}
    kept = []
    for line in lines:
        match = LUKS_DEVICE_LINE.search(line)
        if match:
            existing.setdefault(match.group(1), line.strip())
            continue
        kept.append(line)

    referenced = set(
        re.findall(r"/dev/mapper/([A-Za-z0-9_.+-]+)", "\n".join(kept))
    )

    insert_at = len(kept)
    for index in range(len(kept) - 1, -1, -1):
        if kept[index].strip() == "};":
            insert_at = index
            break

    resolved = {}
    for name, uuid in crypt.items():
        chosen = name if name in referenced else None
        if chosen is None:
            for existing_name, line in existing.items():
                if uuid in line:
                    chosen = existing_name
                    break
        resolved[chosen or name] = '    boot.initrd.luks.devices."{}".device = "/dev/disk/by-uuid/{}";'.format(
            chosen or name, uuid
        )

    for name in sorted(resolved):
        kept.insert(insert_at, resolved[name])
        insert_at += 1

    path.write_text("\n".join(kept) + "\n", encoding="utf-8")
    return path


def generate_facter(staging):
    report = run(["nixos-facter"])
    flake_structure.ensure_facter(
        staging, report, interactive=False, fallback_rel="modules/facter.json"
    )


def extra_boot_lines(settings):
    lines = []
    if settings.serial_console:
        lines.append('boot.kernelParams = [ "console=tty0" "console=ttyS0" ];')
    if settings.firmware == "efi" or not settings.encrypt:
        return lines
    keyfile = paths.TARGET / "boot" / paths.LUKS_KEYFILE
    keyfile.parent.mkdir(parents=True, exist_ok=True)
    keyfile.write_bytes(os.urandom(512))
    os.chmod(keyfile, 0o600)
    lines.append('boot.initrd.secrets."/boot/{}" = null;'.format(paths.LUKS_KEYFILE))
    lines.append("boot.loader.grub.enableCryptodisk = true;")
    lines.append(
        'boot.initrd.luks.devices."{}".keyFile = "/boot/{}";'.format(
            paths.LUKS_NAME, paths.LUKS_KEYFILE
        )
    )
    return lines


def install_bios_keyfile(settings):
    """Let GRUB open the root device without a typed passphrase."""
    if settings.firmware == "efi" or not settings.encrypt:
        return
    device = settings.extras.get("root_device")
    if not device:
        return
    keyfile = paths.TARGET / "boot" / paths.LUKS_KEYFILE
    if not keyfile.exists():
        return
    run(
        ["cryptsetup", "luksConvertKey", "--hash", "sha256", "--pbkdf", "pbkdf2", device],
        input_text=settings.passphrase,
    )
    run(
        [
            "cryptsetup",
            "luksAddKey",
            "--hash",
            "sha256",
            "--pbkdf",
            "pbkdf2",
            device,
            str(keyfile),
        ],
        input_text=settings.passphrase,
    )


def multiboot_needed(target_disk):
    """True when another internal ESP exists besides the one we created."""
    try:
        report = json.loads(
            output(["lsblk", "--tree", "-J", "-o", "NAME,PATH,TYPE,RM,TRAN,PARTTYPE,PKNAME"])
        )
    except (HardwareError, ValueError):
        return False
    esp = "c12a7328-f81f-11d2-ba4b-00a0c93ec93b"
    target = os.path.realpath(target_disk) if target_disk else ""
    for node in report.get("blockdevices", []):
        if node.get("type") != "disk" or node.get("rm"):
            continue
        if (node.get("tran") or "").lower() == "usb":
            continue
        if os.path.realpath(node.get("path") or "") == target:
            continue
        for child in node.get("children") or []:
            if (child.get("parttype") or "").lower() == esp:
                return True
    return False


def prepare(staging, settings, reporter):
    """Generate and inject the hardware and bootloader modules."""
    helper = template.helpers()["regenerateHardware"]
    extra = extra_boot_lines(settings)
    extra_file = None

    if helper:
        reporter.log("running the bundled regenerate-hardware helper")
        arguments = ["--root", staging, "--target-root", str(paths.TARGET),
                     "--firmware", settings.firmware]
        if settings.firmware == "bios":
            arguments += ["--boot-device", str(settings.extras.get("disk_real", settings.disk))]
        if extra:
            extra_file = Path(staging) / ".ojuny-extra-boot.nix"
            extra_file.write_text("\n".join(extra) + "\n", encoding="utf-8")
            arguments += ["--extra-boot-config", str(extra_file)]
        template.run_helper(helper, arguments)
        if extra_file is not None and extra_file.exists():
            extra_file.unlink()
    else:
        reporter.log("generating the hardware module")
        text = generate_hardware(paths.TARGET)
        flake_structure.ensure_hardware(
            staging,
            hardware_module(
                text,
                settings.firmware,
                settings.extras.get("disk_real", settings.disk),
                extra,
            ),
            interactive=False,
            fallback_rel="modules/00-hardware.nix",
        )

    sanitize_hardware_module(staging)
    generate_facter(staging)
    install_bios_keyfile(settings)

    if multiboot_needed(settings.extras.get("disk_real", settings.disk)):
        reporter.log("checking the multiboot helper")
        if not flake_structure.ensure_multiboot(staging, interactive=False):
            reporter.log(
                "warning: this template has no multiboot module; other systems stay unregistered"
            )

